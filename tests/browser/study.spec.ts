import { test, expect } from './fixtures'
import { selectStructure } from './viewer-actions'

test('search focuses a part and opens a study card with recall practice', async ({ signedInPage: page }, info) => {
  await page.goto('/cat/digestive?embed=1')
  await expect(page.getByRole('img', { name: 'cat digestive anatomy' })).toBeVisible()
  await selectStructure(page, 'Stomach')
  const note = page.getByRole('region', { name: 'Stomach', exact: true })
  await expect(note).toBeVisible()
  await expect(page.getByLabel('Zoom level')).toHaveText('180%')
  await expect(note.getByRole('heading', { name: 'Description', exact: true })).toBeVisible()
  await expect(note).toContainText('Stores and mixes food with acid and enzymes')
  await expect.poll(async () => {
    const dot = await page.getByRole('button', { name: 'Stomach', exact: true }).boundingBox()
    const canvas = await page.getByRole('group', { name: 'Anatomy canvas', exact: true }).boundingBox()
    return Math.hypot(dot!.x + dot!.width / 2 - canvas!.x - canvas!.width / 2, dot!.y + dot!.height / 2 - canvas!.y - canvas!.height / 2)
  }).toBeLessThan(2)
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
  await page.screenshot({ path: `test-results/${info.project.name}-study-note.png`, fullPage: true })
  if (info.project.use.hasTouch) {
    await note.getByRole('button', { name: 'Read note', exact: true }).click()
    await expect(note.getByRole('heading', { name: 'Purpose', exact: true })).toBeVisible()
    await note.getByRole('link', { name: /Read more:/ }).scrollIntoViewIfNeeded()
    await expect(note.getByRole('link', { name: /Read more:/ })).toBeVisible()
    await page.screenshot({ path: `test-results/${info.project.name}-expanded-note.png`, fullPage: true })
  }
  await note.getByRole('tab', { name: 'Try recall', exact: true }).click()
  await expect(note).toContainText('What happens here before food reaches the small intestine?')
  await expect(note.getByText('Stores and mixes food with acid and enzymes', { exact: false })).not.toBeVisible()
  await note.getByRole('button', { name: 'Check your reasoning', exact: true }).click()
  await expect(note.getByRole('status')).toContainText('begin protein digestion')
  await note.getByRole('tab', { name: 'Try recall', exact: true }).focus()
  await page.keyboard.press('ArrowLeft')
  await expect(note.getByRole('tab', { name: 'Overview', exact: true })).toBeFocused()
  await expect(note.getByRole('tabpanel')).toContainText('Description')
  await page.getByRole('button', { name: 'Close study note', exact: true }).click()
  await expect(note).not.toBeVisible()
  await expect(page.getByRole('button', { name: 'Stomach', exact: true })).toBeFocused()
})

test('search supports empty results, keyboard selection, and escape without losing the note', async ({ signedInPage: page }) => {
  await page.goto('/dog/cardiovascular?embed=1')
  await page.getByRole('button', { name: 'Structures', exact: true }).click()
  const search = page.getByRole('combobox', { name: 'Search structures', exact: true })
  await expect(search).toBeFocused()
  await search.fill('not-a-structure')
  await expect(page.getByText('No matching structures in this system.')).toBeVisible()
  await search.fill('heart')
  await page.keyboard.press('Enter')
  await expect(page.getByRole('region', { name: 'Heart', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Structures', exact: true }).click()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog', { name: 'Find a structure' })).not.toBeVisible()
  await expect(page.getByRole('region', { name: 'Heart', exact: true })).toBeVisible()
})

test('dots can be hidden and searching restores the selected marker', async ({ signedInPage: page }) => {
  await page.goto('/dog/digestive?embed=1')
  await page.getByRole('button', { name: 'Hide dots', exact: true }).click()
  await expect(page.locator('.hotspot')).toHaveCount(0)
  await expect(page.getByRole('img', { name: 'dog digestive anatomy' })).toBeVisible()
  await selectStructure(page, 'Stomach')
  await expect(page.getByRole('button', { name: 'Stomach', exact: true })).toHaveAttribute('aria-expanded', 'true')
  await page.getByRole('button', { name: 'Hide dots', exact: true }).click()
  await expect(page.locator('.study-note')).not.toBeVisible()
  await page.getByRole('button', { name: 'Show dots', exact: true }).click()
  await expect(page.locator('.hotspot')).toHaveCount(5)
})

test('a root return remembers the last selection while deep links and browser history take precedence', async ({ signedInPage: page }) => {
  await page.goto('/dog/skeletal?embed=1')
  await page.getByRole('button', { name: 'Cat', exact: true }).click()
  await page.getByRole('button', { name: 'Digestive System', exact: true }).click()
  await expect(page.getByRole('img', { name: 'cat digestive anatomy' })).toBeVisible()
  await page.goto('/?embed=1')
  await expect(page.getByRole('img', { name: 'cat digestive anatomy' })).toBeVisible()
  await expect(page).toHaveURL(/\/cat\/digestive\?embed=1$/)
  await page.goto('/bird/nervous?embed=1')
  await expect(page.getByRole('img', { name: 'bird nervous anatomy' })).toBeVisible()
  await page.getByRole('button', { name: 'Dog', exact: true }).click()
  await page.goBack()
  await expect(page.getByRole('img', { name: 'bird nervous anatomy' })).toBeVisible()
})
